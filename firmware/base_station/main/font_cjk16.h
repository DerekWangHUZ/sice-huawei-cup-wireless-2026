/*
 * font_cjk16.h -- 16x16 中文点阵字库（SSD1306 页格式，按需收录子集）
 *
 * 设计取舍（替代完整中文字库）：
 *   完整 GB2312 16x16 字库约 260KB，而本屏只用到十余个固定词条
 *   （状态名 + 标题 + 告警词）。故只收录基线字符集，约 0.5KB flash，
 *   对 1M app 分区（当前余量 11%）几乎无影响。
 *   需要增字时：把新字加入 tools/font_gen/gen_cjk16.ps1 的码点表，
 *   重跑脚本，把输出行粘回本文件即可。
 *
 * 字模格式（与 oled_display.c 的绘制函数严格对应）：
 *   16x16 点阵，列优先，共 32 字节：
 *     字节 0..15  = 上半页（行 0..7），第 c 字节对应第 c 列，bit0 在最上方；
 *     字节 16..31 = 下半页（行 8..15），第 (16+c) 字节对应第 c 列，bit0 = 行 8。
 *   正是 SSD1306 页寻址模式下一列一字节的排布，绘制时无需再转置。
 *
 * 字模生成：firmware/base_station/tools/font_gen/gen_cjk16.ps1
 *   （本机宋体网格适配渲染 + 墨水居中；生成时附 ASCII 点阵图人工目视校验。
 *     该脚本刻意保持纯 ASCII，避免 Windows PowerShell 5.1 按 ANSI 解析
 *     带中文注释的脚本时报错。）
 */

